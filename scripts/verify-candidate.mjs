import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { createHash, createPublicKey, verify } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("..", import.meta.url));
const packageJson = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
const installer = process.argv[2] ?? path.join(root, "src-tauri", "target", "release", "bundle", "nsis", `Deadline Panel_${packageJson.version}_x64-setup.exe`);
const config = JSON.parse(readFileSync(path.join(root, "src-tauri", "tauri.conf.json"), "utf8"));
const publicText = Buffer.from(config.plugins.updater.pubkey, "base64").toString("utf8").trim().split(/\r?\n/);
const publicBytes = Buffer.from(publicText[1], "base64");
assert.equal(publicBytes.length, 42);
const key = createPublicKey({ key: Buffer.concat([Buffer.from("302a300506032b6570032100", "hex"), publicBytes.subarray(10)]), format: "der", type: "spki" });
const signatureFile = readFileSync(installer + ".sig");
const lines = Buffer.from(signatureFile.toString().trim(), "base64").toString("utf8").trim().split(/\r?\n/);
const signature = Buffer.from(lines[1], "base64");
assert.equal(signature.length, 74);
assert.equal(signature.subarray(2,10).equals(publicBytes.subarray(2,10)), true, "signature key id must match existing updater public key");
assert.equal(lines[2].startsWith("trusted comment: "), true);
const data = readFileSync(installer);
const signatureAlgorithm = signature.subarray(0,2).toString();
assert.ok(["Ed", "ED"].includes(signatureAlgorithm));
const payload = (bytes) => signatureAlgorithm === "ED" ? createHash("blake2b512").update(bytes).digest() : bytes;
assert.equal(verify(null, payload(data), key, signature.subarray(10)), true, "installer signature invalid");
assert.equal(verify(null, Buffer.concat([signature.subarray(10), Buffer.from(lines[2].slice(17))]), key, Buffer.from(lines[3], "base64")), true, "trusted comment signature invalid");
const tampered = Buffer.from(data); tampered[tampered.length - 1] ^= 1;
assert.equal(verify(null, payload(tampered), key, signature.subarray(10)), false, "tampering must be rejected");
const checksums = [[installer, data], [installer + ".sig", signatureFile]].map(([file, bytes]) => `${createHash("sha256").update(bytes).digest("hex")}  ${path.basename(file)}`).join("\n") + "\n";
writeFileSync(path.join(path.dirname(installer), "SHA256SUMS.txt"), checksums);
console.log("通过：候选安装包与原更新公钥匹配；文件签名、可信备注签名有效；修改文件会被拒绝。");
console.log(checksums.trim());
